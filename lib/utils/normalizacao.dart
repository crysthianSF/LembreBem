String normalizarTexto(String valor) {
  var texto = valor.toLowerCase();

  const substituicoes = {
    'á': 'a',
    'à': 'a',
    'â': 'a',
    'ã': 'a',
    'ä': 'a',
    'é': 'e',
    'è': 'e',
    'ê': 'e',
    'ë': 'e',
    'í': 'i',
    'ì': 'i',
    'î': 'i',
    'ï': 'i',
    'ó': 'o',
    'ò': 'o',
    'ô': 'o',
    'õ': 'o',
    'ö': 'o',
    'ú': 'u',
    'ù': 'u',
    'û': 'u',
    'ü': 'u',
    'ç': 'c',
    'ñ': 'n',
  };

  substituicoes.forEach((origem, destino) {
    texto = texto.replaceAll(origem, destino);
  });

  return texto.replaceAll(RegExp(r'\s+'), ' ').trim();
}
